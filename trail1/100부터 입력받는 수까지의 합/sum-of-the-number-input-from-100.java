import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
     
    //파이프라인
    Scanner sc = new Scanner(System.in);

    //변수 선언
    int N = sc.nextInt(), sumVal = 0;



    for(int i = N ; i<=100 ; i++){

        sumVal = sumVal + i;





    }
    System.out.print(sumVal);






    }
}